def _last_trading_day() -> str:
    """Return most recent NSE trading day (Mon–Fri) as YYYY-MM-DD."""
    d = ist_now()
    if is_market_open():
        return d.strftime("%Y-%m-%d")
    if d.weekday() < 5 and (d.hour > 9 or (d.hour == 9 and d.minute >= 15)):
        return d.strftime("%Y-%m-%d")
    d -= timedelta(days=1)
    while d.weekday() >= 5:
        d -= timedelta(days=1)
    return d.strftime("%Y-%m-%d")

def _parse_ts(ts_val):
    """Parse Dhan timestamp to HH:MM — handles both epoch int and string formats."""
    try:
        if isinstance(ts_val, (int, float)):
            return datetime.fromtimestamp(ts_val, IST).strftime("%H:%M")
        s = str(ts_val)
        if " " in s: return s.split(" ")[1][:5]
        if "T" in s: return s.split("T")[1][:5]
        return s[:5]
    except:
        return ""

def _pct_from_reference(price, reference):
    try:
        price_num = float(price)
        reference_num = float(reference)
        return round((price_num - reference_num) / reference_num * 100, 2) if reference_num > 0 else 0.0
    except (TypeError, ValueError, ZeroDivisionError):
        return 0.0

def _compute_breakout(tok):
    global _bk_cache
    if not SYMBOLS or not tok: return
    _bk_cache["status"] = "fetching"

    cid         = CREDS.get("client_id", "")
    headers     = {"access-token": tok, "client-id": cid, "Content-Type": "application/json"}
    market_open = is_market_open()
    today       = _last_trading_day()
    from_dt     = f"{today} 09:15:00"
    to_dt       = f"{today} 15:30:00"

    # Use vol data from screener if already available — don't wait for it
    vol_map = {x["symbol"]: (x.get("todayVol", 0), x.get("avgVol7d", 0))
               for x in cache.get("data", [])}
    print(f"[bk] date={today} mode={'LIVE' if market_open else 'CLOSED'} "
          f"range={RANGE_START}-{RANGE_END} vol_map={len(vol_map)}")

    results     = []
    ok_count    = 0
    no_range    = 0
    no_break    = 0
    empty_count = 0
    err_count   = 0
    _ts_logged  = False

    for sym_info in SYMBOLS:
        sym = sym_info["symbol"]
        try:
            r = requests.post(
                f"{DHAN_BASE}/v2/charts/intraday",
                json={"securityId": str(sym_info["security_id"]),
                      "exchangeSegment": "NSE_EQ", "instrument": "EQUITY",
                      "interval": "1", "oi": False,
                      "fromDate": from_dt, "toDate": to_dt},
                headers=headers, timeout=10)
            if r.status_code == 429:
                print(f"[bk] {sym} 429 — sleeping 5s"); time.sleep(5); continue
            if r.status_code != 200:
                err_count += 1
                if err_count <= 2:
                    print(f"[bk] {sym} HTTP {r.status_code}: {r.text[:120]}")
                continue

            d          = r.json()
            timestamps = d.get("timestamp", [])
            highs      = d.get("high",   [])
            lows       = d.get("low",    [])
            closes     = d.get("close",  [])

            if not timestamps:
                empty_count += 1
                if empty_count <= 2:
                    print(f"[bk] {sym} empty — keys={list(d.keys())}")
                continue

            # Log timestamp format on very first response received
            if not _ts_logged:
                print(f"[bk] ts_fmt: type={type(timestamps[0]).__name__} sample={str(timestamps[0])[:25]}")
                _ts_logged = True

            # ── Step 1: Build 9:15–9:45 opening range ────────────────────────
            range_highs = []; range_lows = []; range_ref = None
            for i, ts in enumerate(timestamps):
                t = _parse_ts(ts)
                if RANGE_START <= t <= RANGE_END:
                    range_highs.append(highs[i])
                    range_lows.append(lows[i])
                    range_ref = closes[i]

            if len(range_highs) < 2:
                no_range += 1; continue
            if not range_ref or range_ref <= 0:
                no_range += 1; continue

            range_high = round(max(range_highs), 2)
            range_low  = round(min(range_lows),  2)
            range_ref  = round(range_ref, 2)

            # ── Step 2: Find close-based breakout ────────────────────────────
            direction = signal_time = signal_price = None
            boundary_signal_pct = 0.0
            ltp = range_ref

            for i, ts in enumerate(timestamps):
                t = _parse_ts(ts)
                if t <= RANGE_END: continue
                ltp = closes[i]

                if market_open:
                    if t != CONFIRM_TIME: continue
                    if closes[i] > range_high:
                        direction = "bull"; signal_time = t
                        signal_price = round(closes[i], 2)
                        boundary_signal_pct = _pct_from_reference(closes[i], range_high)
                    elif closes[i] < range_low:
                        direction = "bear"; signal_time = t
                        signal_price = round(closes[i], 2)
                        boundary_signal_pct = _pct_from_reference(closes[i], range_low)
                    break
                else:
                    if direction is None:
                        if closes[i] > range_high:
                            direction = "bull"; signal_time = t
                            signal_price = round(closes[i], 2)
                            boundary_signal_pct = _pct_from_reference(closes[i], range_high)
                        elif closes[i] < range_low:
                            direction = "bear"; signal_time = t
                            signal_price = round(closes[i], 2)
                            boundary_signal_pct = _pct_from_reference(closes[i], range_low)

            if not direction:
                no_break += 1; continue

            # The UI displays the 9:45 close as its reference, so both percentages
            # must use that same visible price. Boundary penetration is retained
            # separately for diagnostics and never mislabeled as Break %.
            signal_pct = _pct_from_reference(signal_price, range_ref)
            current_pct = _pct_from_reference(ltp, range_ref)
            boundary = range_high if direction == "bull" else range_low
            current_boundary_pct = _pct_from_reference(ltp, boundary)

            today_vol, avg_vol = vol_map.get(sym, (0, 0))
            vol_ratio     = round(today_vol / avg_vol, 2) if avg_vol else 0.0
            vol_confirmed = vol_ratio >= 1.5
            ok_count     += 1

            results.append({
                "symbol":        sym,
                "ltp":           round(ltp, 2),
                "rangeHigh":     range_high,
                "rangeLow":      range_low,
                "rangeRef":      range_ref,
                "direction":     direction,
                "signal_time":   signal_time,
                "signal_price":  signal_price,
                "signalPct":     signal_pct,
                "move_pct":      signal_pct,
                "current_pct":   current_pct,
                "breakoutPct":   signal_pct,
                "boundary_break_pct": boundary_signal_pct,
                "current_boundary_pct": current_boundary_pct,
                "volRatio":      vol_ratio,
                "vol_confirmed": vol_confirmed,
                "todayVol":      today_vol,
                "mode":          "live" if market_open else "closed",
            })
            time.sleep(0.25)

        except Exception as e:
            print(f"[bk] {sym} ERR {type(e).__name__}: {e}"); no_break += 1; continue

    print(f"[bk] done: ok={ok_count} no_range={no_range} no_break={no_break} empty={empty_count} http_err={err_count}")
    results.sort(key=lambda x: abs(x["current_pct"]), reverse=True)
    _bk_cache.update({
        "data":          results,
        "updated_at":    ist_now().strftime("%H:%M:%S IST"),
        "status":        "ok",
        "count":         len(results),
        "bulls":         sum(1 for r in results if r["direction"] == "bull"),
        "bears":         sum(1 for r in results if r["direction"] == "bear"),
        "vol_confirmed": sum(1 for r in results if r["vol_confirmed"]),
        "market_open":   market_open,
        "trading_date":  today,
        "range_end":     RANGE_END,
    })
    print(f"[bk] {len(results)} breakouts ({_bk_cache['bulls']} bull / {_bk_cache['bears']} bear)")

def _run_bk_locked(tok):
    with _bk_lock: _compute_breakout(tok)

def _bk_stale():
    if not _bk_cache.get("updated_at"): return True
    cached_date = _bk_cache.get("trading_date", "")
    if cached_date and cached_date != _last_trading_day(): return True
    last = _bk_cache.get("updated_at")
    try:
        t = datetime.strptime(last, "%H:%M:%S IST").replace(
            year=ist_now().year, month=ist_now().month, day=ist_now().day, tzinfo=IST)
        threshold = 300 if is_market_open() else 3600
        return (ist_now() - t).seconds > threshold
    except: return True

