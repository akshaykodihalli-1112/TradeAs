def _compute_ois(tok: str):
    """
    OI Strategy Scanner.
    Live: waits for PS to finish (has option chain data with strike vol ratios).
    Closed: uses screener cache directly.
    """
    global _ois_cache
    _ois_cache["status"] = "fetching"
    market_open = is_market_open()
    print(f"[ois] starting OI Strategy scan... market_open={market_open}")

    source_data = []

    if market_open:
        # Wait for PS to finish — OIS needs strike vol data from option chains
        wait = 0
        while _ps_lock.locked() and wait < 600:
            if wait == 0: print(f"[ois] waiting for PS option chains...")
            time.sleep(10); wait += 10
        source_data = _ps_cache.get("data", [])
        if not source_data:
            print(f"[ois] PS has no data — using live screener fallback")
    else:
        # Closed market — use PS data if available (has option chains), else screener
        source_data = _ps_cache.get("data", [])
        if source_data:
            print(f"[ois] closed — using PS data ({len(source_data)} candidates)")

    # Screener fallback — closed market with no PS data
    if not source_data:
        chg_min = 0.5 if not market_open else 1.0
        vol_min  = 0.5 if not market_open else 0.8
        for row in cache.get("data", []):
            chg = row.get("change", 0)
            vr  = row.get("volumeRatio", 0)
            tv  = row.get("todayVol", 0)
            av  = row.get("avgVol7d", 0)
            ltp = row.get("ltp", 0)
            if not ltp: continue
            if abs(chg) < chg_min: continue
            if vr == 0 and av > 0: vr = round(tv / av, 2)
            if vr < vol_min and not (market_open and vr == 0 and tv > 0): continue
            source_data.append({
                **row,
                "direction":  "bull" if chg > 0 else "bear",
                "opt_data":   {},
                "opt_score":  0,
                "eq_score":   2 if abs(chg) >= 2.5 else 1,
                "strikes":    [],
                "volRatio":   vr,
            })
        print(f"[ois] screener fallback: {len(source_data)} candidates")
    print(f"[ois] scoring {len(source_data)} candidates...")
    results = []

    for row in source_data:
        sym      = row.get("symbol", "")
        spot     = row.get("ltp", 0)
        if not spot: continue

        direction = row.get("direction", "bull")
        opt_data  = row.get("opt_data") or {}
        sector    = _OIS_SECTOR_MAP.get(sym, "Unknown")

        score = _ois_compute_score(row, opt_data)
        if score < _OIS_SCORE_MIN: continue

        # Force 1-strike ITM selection (core of the strategy)
        itm      = _ois_itm_strike(spot, direction)
        opt_type = itm["opt_type"]

        # Prefer option-chain derived best_strike only if it's actually ITM
        bs        = row.get("best_strike") or itm["strike"]
        bl        = row.get("best_ltp", 0)
        bd        = row.get("best_delta") or itm["delta_est"]
        bg        = row.get("best_gamma", 0)
        biv       = row.get("best_iv", 0)
        bs_is_itm = (direction == "bull" and bs < spot) or (direction == "bear" and bs > spot)
        if not bs_is_itm:
            # Override: always use ITM strike, not whatever PS selected
            bs = itm["strike"]; bd = itm["delta_est"]; bl = 0

        pcr      = opt_data.get("pcr", 0)
        ce_oi_ch = opt_data.get("ce_oi_change", 0)
        pe_oi_ch = opt_data.get("pe_oi_change", 0)
        ce_vr    = opt_data.get("ce_vol_ratio", 0)
        pe_vr    = opt_data.get("pe_vol_ratio", 0)
        strike_vr = ce_vr if direction == "bull" else pe_vr

        # Human-readable OI signal label
        if direction == "bull":
            oi_label = ("Long Buildup"   if ce_oi_ch > 0 and ce_vr > 3 else
                        "CE Vol Surge"   if ce_vr > 3 else
                        "Long Buildup"   if ce_oi_ch > 0 else "CE Signal")
